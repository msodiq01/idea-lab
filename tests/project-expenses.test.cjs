"use strict";
const assert=require("node:assert/strict");
const model=require("../assets/idea-project-expenses.js");
const projectId="project-1";
const entry=model.createEntry({title:"No‘xot",category:"Xomashyo",supplier:"Ta’minotchi A",quantity:20,unit:"kg",unitPrice:15000,receiptReference:"INV-001"},{projectId});
assert.equal(entry.total,300000);
assert.equal(entry.status,"Rejalashtirilgan");
assert.throws(()=>model.createEntry({title:"",category:"Xomashyo",supplier:"A",quantity:1,unitPrice:1},{projectId}),/majburiy/);
assert.throws(()=>model.createEntry({title:"A",category:"X",supplier:"B",quantity:1.5,unitPrice:10},{projectId}),/butun/);
const second=model.createEntry({title:"Quti",category:"Qadoqlash",supplier:"B",quantity:100,unit:"dona",unitPrice:500},{projectId});
const other=model.createEntry({title:"Other",category:"Xizmat",supplier:"C",quantity:2,unitPrice:1000},{projectId:"other"});
let rows=[entry,second,other];
let summary=model.summarize(rows,projectId);
assert.equal(summary.count,2);assert.equal(summary.totalPlanned,350000);assert.equal(summary.paidAmount,0);
rows=model.updateStatus(rows,entry.id,"To‘landi",projectId);
summary=model.summarize(rows,projectId);
assert.equal(summary.paidAmount,300000);assert.equal(summary.verifiedAmount,0);
rows=model.updateStatus(rows,entry.id,"Hujjat bilan tasdiqlandi",projectId);
assert.equal(model.summarize(rows,projectId).verifiedAmount,300000);
assert.throws(()=>model.updateStatus(rows,"missing","To‘landi",projectId),/topilmadi/);
console.log("Project expense ledger model tests passed.");
